// Builds site/data/posts.js from the admin-edited content in site/content/.
// Netlify runs this on every deploy (see netlify.toml); run it locally with
// `node scripts/build-data.mjs` after editing content by hand.
import fs from 'node:fs';
import path from 'node:path';

const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'site');
const read = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));

// Keep in step with the category options in site/admin/config.yml.
const CATEGORIES = ['Editorial', 'Beauty', 'Celebrity', 'Advertising'];

const site = read(path.join(root, 'content/site.json'));
const postsDir = path.join(root, 'content/posts');

const fmtDate = (iso) => {
  const [y, m, d] = String(iso || '').slice(0, 10).split('-');
  return [y, m, d].filter(Boolean).join('. ');
};

const posts = fs.readdirSync(postsDir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => {
    const p = read(path.join(postsDir, f));
    return {
      id: f.replace(/\.json$/, ''),
      pinned: Boolean(p.pinned),
      sortKey: String(p.date || ''),
      category: p.category || '',
      date: fmtDate(p.date),
      title: p.title || '',
      cover: p.cover || '',
      images: (p.images || []).map((i) => (typeof i === 'string' ? i : i.image)).filter(Boolean),
      credits: (p.credits || []).filter((c) => c && c.role),
      tags: p.tags || [],
      instagram: p.instagram || '',
    };
  })
  // Pinned posts first, then newest first; the portfolio shows posts in this order.
  .sort((a, b) => (b.pinned - a.pinned) || b.sortKey.localeCompare(a.sortKey) || a.id.localeCompare(b.id))
  .map(({ sortKey, pinned, ...p }) => p);

const out = `// Generated by scripts/build-data.mjs from site/content/ — edit content in /admin, not here.
window.SITE = ${JSON.stringify({ ...site, filters: ['All', ...CATEGORIES] }, null, 2)};
window.POSTS = ${JSON.stringify(posts, null, 2)};
window.IMAGE_CDN = ${process.env.NETLIFY === 'true'};
`;
fs.writeFileSync(path.join(root, 'data/posts.js'), out);
console.log(`site/data/posts.js: ${posts.length} posts`);
